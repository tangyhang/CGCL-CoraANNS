#include <cstdint>
#include <cstdlib>
#include <exception>
#include <iostream>
#include <stdexcept>
#include <string>

#include "rabitqlib/defines.hpp"
#include "rabitqlib/index/ivf/ivf.hpp"
#include "rabitqlib/utils/io.hpp"
#include "rabitqlib/utils/stopw.hpp"

using PID = rabitqlib::PID;
using index_type = rabitqlib::ivf::IVF;
using data_type = rabitqlib::RowMajorArray<float>;
using gt_type = rabitqlib::RowMajorArray<uint32_t>;

int main(int argc, char **argv) {
    if (argc < 6) {
        std::cerr << "Usage: " << argv[0] << " <arg1> <arg2> <arg3> <arg4> <arg5>\n"
                  << "arg1: path for data file, format .fvecs/.fbin\n"
                  << "arg2: path for centroids file generated by ivf.py\n"
                  << "arg3: path for cluster ids file generated by ivf.py\n"
                  << "arg4: total number of bits for quantization\n"
                  << "arg5: path for saving index\n"
                  << "arg6: metric type (\"l2\" or \"ip\"), l2 by default\n"
                  << "arg7: if use faster quantization (\"true\" or \"false\"), false by default\n"
                  << "Environment: RABITQ_GPU_BATCH_SIZE controls vectors per GPU batch\n";
        return 1;
    }

    try {
        rabitqlib::StopW command_stopw;
        rabitqlib::MetricType metric_type = rabitqlib::METRIC_L2;
        if (argc > 6) {
            const std::string metric_str(argv[6]);
            if (metric_str == "ip" || metric_str == "IP") {
                metric_type = rabitqlib::METRIC_IP;
            }
        }
        std::cout << "Metric Type: " << (metric_type == rabitqlib::METRIC_IP ? "IP\n" : "L2\n");

        bool faster_quant = false;
        if (argc > 7 && std::string(argv[7]) == "true") {
            faster_quant = true;
            std::cout << "Using faster quantize for indexing...\n";
        }

        const char *data_file = argv[1];
        const char *centroids_file = argv[2];
        const char *cids_file = argv[3];
        const size_t total_bits = std::stoull(argv[4]);
        const char *index_file = argv[5];

        data_type data;
        data_type centroids;
        gt_type cids;
        rabitqlib::StopW input_load_stopw;
        rabitqlib::load_auto<float, data_type>(data_file, data);
        rabitqlib::load_vecs<float, data_type>(centroids_file, centroids);
        rabitqlib::load_vecs<PID, gt_type>(cids_file, cids);
        const float input_loading_seconds = input_load_stopw.get_elapsed_sec();

        const size_t num_points = data.rows();
        const size_t dim = data.cols();
        const size_t num_clusters = centroids.rows();
        if (static_cast<size_t>(centroids.cols()) != dim) {
            throw std::runtime_error("centroid dimension does not match base data");
        }
        if (static_cast<size_t>(cids.rows()) != num_points || cids.cols() != 1) {
            throw std::runtime_error("cluster-id file must contain one id per base vector");
        }

        std::cout << "data loaded\n"
                  << "\tN: " << num_points << '\n'
                  << "\tDIM: " << dim << '\n'
                  << "\tclusters: " << num_clusters << '\n';

        // Keep the historical "Indexing time" measurement (initialization +
        // construction, excluding save), and also report its components and
        // the end-to-end time including index serialization.
        rabitqlib::StopW total_stopw;
        rabitqlib::StopW phase_stopw;
        index_type ivf(num_points, dim, num_clusters, total_bits, metric_type);
        const float initialization_seconds = phase_stopw.get_elapsed_sec();

        phase_stopw.reset();
        ivf.construct_gpu(data.data(), centroids.data(), cids.data(), faster_quant);
        const float construction_seconds = phase_stopw.get_elapsed_sec();
        const float indexing_minutes = total_stopw.get_elapsed_sec() / 60.0F;
        std::cout << "ivf constructed on GPU\n";

        phase_stopw.reset();
        ivf.save(index_file);
        const float save_seconds = phase_stopw.get_elapsed_sec();
        const float total_seconds = total_stopw.get_elapsed_sec();
        const float command_seconds = command_stopw.get_elapsed_sec();

        std::cout << "Indexing time " << indexing_minutes << '\n'
                  << "GPU indexing timing summary (seconds)\n"
                  << "\tInput loading: " << input_loading_seconds << '\n'
                  << "\tIVF initialization/rotation matrix: " << initialization_seconds << '\n'
                  << "\tGPU construction: " << construction_seconds << '\n'
                  << "\tIndex serialization: " << save_seconds << '\n'
                  << "\tTotal excluding input loading: " << total_seconds << '\n'
                  << "\tEnd-to-end command total: " << command_seconds << '\n';
        return 0;
    } catch (const std::exception &error) {
        std::cerr << "ivf_rabitq_indexing_gpu failed: " << error.what() << '\n';
        return 1;
    }
}
